#!/bin/sh
#
# test/lib.sh — harness for the ponder conformance suite.
#
# POSIX sh. No frameworks, no npm, no dependency on the engine's internals.
# Sourced by test/conformance.sh, which must export these first:
#
#   REPO_ROOT    absolute path to the ponder checkout
#   PONDER_BIN   the binary under test (default $REPO_ROOT/bin/ponder)
#   FIXTURES     absolute path to test/fixtures
#   SUITE_TMP    scratch directory for the whole run
#   VERBOSE      1 to echo every ponder invocation
#   KEEP         1 to leave per-test work directories on disk
#
# Everything here is generic plumbing: colours, counters, assertions, a JSON
# probe, and the runner for a single ponder invocation. Test bodies and the
# session builders live in conformance.sh.

# ---------------------------------------------------------------- colours ---

if [ -t 1 ] && [ -z "${NO_COLOR:-}" ]; then
  C_RED=$(printf '\033[31m')
  C_GRN=$(printf '\033[32m')
  C_YEL=$(printf '\033[33m')
  C_CYN=$(printf '\033[36m')
  C_DIM=$(printf '\033[2m')
  C_BLD=$(printf '\033[1m')
  C_OFF=$(printf '\033[0m')
else
  C_RED=''; C_GRN=''; C_YEL=''; C_CYN=''; C_DIM=''; C_BLD=''; C_OFF=''
fi

MARK_OK='✓'
MARK_BAD='✗'
MARK_WARN='⚠'

# --------------------------------------------------------------- counters ---

TESTS_RUN=0
TESTS_PASSED=0
TESTS_FAILED=0
WARNINGS=0
ASSERTS=0            # assertions in the current test
ASSERT_FAILS=0       # failed assertions in the current test
FAIL_MSGS=''         # buffered failure detail for the current test
FAILED_NAMES=''      # newline-separated names of failed tests
TEST_NAME=''

# ------------------------------------------------------------ environment ---

NODE=${PONDER_NODE:-node}

if command -v shasum >/dev/null 2>&1; then
  HASHER='shasum -a 256'
elif command -v sha256sum >/dev/null 2>&1; then
  HASHER='sha256sum'
else
  HASHER='cksum'
fi

ESC=$(printf '\033')

# POSIX only requires sleep to accept whole seconds. BSD and GNU sleep both take
# fractions, and the watchdog polls much more pleasantly at 0.1s, so probe once
# and fall back to a whole second where fractions are refused.
if sleep 0.1 2>/dev/null; then
  POLL_SLEEP='0.1'
else
  POLL_SLEEP='1'
fi

# A pty runner, for the tests that care whether colour is decided by the
# terminal rather than by the pipe. `script` differs between BSD and GNU and is
# missing on some minimal images, so probe it once and let callers degrade.
TTY_STYLE=''
if command -v script >/dev/null 2>&1; then
  if script -q /dev/null true >/dev/null 2>&1; then
    TTY_STYLE=bsd
  elif script -qec true /dev/null >/dev/null 2>&1; then
    TTY_STYLE=gnu
  fi
fi

WORK=''              # current test's work directory
SLUG=''              # current test's session slug
STATUS=0             # exit status of the last ponder run
OUT=''               # stdout of the last ponder run
ERR=''               # stderr of the last ponder run
ALL=''               # stdout + stderr of the last ponder run
ELAPSED=0            # whole seconds the last ponder run took
TIMED_OUT=0          # 1 when a limited run was killed by the watchdog
LAST_CMD=''
_WORK_SEQ=0

# --------------------------------------------------------- the JSON probe ---
#
# One tiny node program, written into the scratch directory at startup, gives
# the shell a JSON reader without adding a dependency to the repo. It is a test
# tool only — the engine never sees it.

json_helper_init() {
  JSON_HELPER="$SUITE_TMP/json-probe.cjs"
  cat > "$JSON_HELPER" <<'PROBE_EOF'
// JSON probe for the ponder conformance suite. Generated by test/lib.sh.
const fs = require("fs");
const argv = process.argv.slice(2);
const cmd = argv[0];

function die(msg, code) {
  process.stderr.write("json-probe: " + msg + "\n");
  process.exit(code);
}

function load(p) {
  let raw;
  try {
    raw = fs.readFileSync(p, "utf8");
  } catch (e) {
    die("cannot read " + p, 3);
  }
  try {
    return JSON.parse(raw);
  } catch (e) {
    die("unparseable JSON in " + p + ": " + e.message, 3);
  }
}

function lines(p) {
  let raw;
  try {
    raw = fs.readFileSync(p, "utf8");
  } catch (e) {
    die("cannot read " + p, 3);
  }
  const out = [];
  raw.split("\n").forEach((l, i) => {
    if (l.trim() === "") return;
    try {
      out.push(JSON.parse(l));
    } catch (e) {
      die("line " + (i + 1) + " of " + p + " is not JSON: " + l.slice(0, 200), 1);
    }
  });
  return out;
}

function emit(v) {
  if (v === undefined || v === null) process.exit(5);
  process.stdout.write(typeof v === "object" ? JSON.stringify(v) : String(v));
  process.exit(0);
}

function evaluate(d, expr) {
  let v;
  try {
    v = new Function("d", "return (" + expr + ");")(d);
  } catch (e) {
    die("expression failed [" + expr + "]: " + e.message, 4);
  }
  return v;
}

if (cmd === "get") {
  emit(evaluate(load(argv[1]), argv[2]));
} else if (cmd === "jsonl-eval") {
  emit(evaluate(lines(argv[1]), argv[2]));
} else if (cmd === "jsonl-count") {
  emit(lines(argv[1]).length);
} else if (cmd === "find") {
  // Breadth-first search for the first scalar value under any of the given
  // key names, case-insensitively. Used where the spec fixes a value but not
  // the shape of the object carrying it.
  const d = load(argv[1]);
  const keys = argv.slice(2).map((k) => k.toLowerCase());
  const queue = [d];
  while (queue.length) {
    const cur = queue.shift();
    if (cur === null || typeof cur !== "object") continue;
    const names = Object.keys(cur);
    for (const k of names) {
      const v = cur[k];
      const scalar =
        typeof v === "string" || typeof v === "number" || typeof v === "boolean";
      if (scalar && keys.indexOf(k.toLowerCase()) !== -1) emit(v);
    }
    for (const k of names) queue.push(cur[k]);
  }
  process.exit(5);
} else if (cmd === "parse") {
  let s = "";
  process.stdin.setEncoding("utf8");
  process.stdin.on("data", (d) => (s += d));
  process.stdin.on("end", () => {
    if (s.trim() === "") die("nothing on stdout to parse", 1);
    try {
      JSON.parse(s);
    } catch (e) {
      die("stdout is not JSON: " + e.message + "\n--- stdout ---\n" + s.slice(0, 600), 1);
    }
    process.exit(0);
  });
} else {
  die("unknown probe command: " + cmd, 2);
}
PROBE_EOF
}

# jget <file> <js-expression-over-d>   -> prints the value, exits non-zero if absent
jget() { "$NODE" "$JSON_HELPER" get "$1" "$2" 2>/dev/null; }

# jget_loud <file> <expr>              -> same, but lets probe errors reach stderr
jget_loud() { "$NODE" "$JSON_HELPER" get "$1" "$2"; }

# jl <jsonl-file> <js-expression-over-d>  where d is the array of parsed lines
jl() { "$NODE" "$JSON_HELPER" jsonl-eval "$1" "$2" 2>/dev/null; }

# jlines <jsonl-file>                  -> number of JSON lines (fails if any line is bad)
jlines() { "$NODE" "$JSON_HELPER" jsonl-count "$1" 2>/dev/null; }

# jfind <file> <key> [key...]          -> first scalar under any of those keys
jfind() { "$NODE" "$JSON_HELPER" find "$@" 2>/dev/null; }

# json_parses <text>                   -> exit 0 when the text is one JSON document
json_parses() { printf '%s' "$1" | "$NODE" "$JSON_HELPER" parse 2>&1; }

# --------------------------------------------------------- work directories --

# new_workdir <short-name> [slug]
# Fresh project directory with a small fake source tree, so evidence paths in
# the fixtures point at files that exist and `ponder apply` has something it
# could damage.
new_workdir() {
  _WORK_SEQ=$((_WORK_SEQ + 1))
  WORK="$SUITE_TMP/w$_WORK_SEQ-$1"
  SLUG=${2:-ui-conformance}
  mkdir -p "$WORK/src/routes/settings" "$WORK/src/routes/onboarding"

  cat > "$WORK/package.json" <<'EOF'
{ "name": "fixture-app", "version": "0.0.1", "private": true }
EOF
  cat > "$WORK/README.md" <<'EOF'
# fixture-app

A stand-in project. The conformance suite checksums this tree to prove that
`ponder apply` writes a plan and never touches source.
EOF
  cat > "$WORK/src/routes/settings/billing.tsx" <<'EOF'
export function Billing() {
  return <section><h2>Billing</h2><p>No invoices</p></section>;
}
EOF
  cat > "$WORK/src/routes/settings/profile.tsx" <<'EOF'
export function Profile() {
  return <form><label>Display name</label><input name="display" /></form>;
}
EOF
  cat > "$WORK/src/routes/onboarding/welcome.tsx" <<'EOF'
export function Welcome() {
  return <main><h1>Welcome</h1><button>Get started</button></main>;
}
EOF

  cp "$FIXTURES/units-3.json" "$WORK/units.json"
  cp "$FIXTURES/deliberation.json" "$WORK/deliberation.json"
  note "workdir $WORK (slug $SLUG)"
}

# markerless_workdir <short-name> [slug]
# Like new_workdir, but with no project marker anywhere inside it: no
# package.json, no .git. The source tree lives one level down, in $NESTED, so a
# test can run the engine from a directory that has to look upwards to decide
# what the project is. $WORK itself is the "unrelated ancestor" — whatever a
# test puts there is what the walk will find.
NESTED=''
markerless_workdir() {
  _WORK_SEQ=$((_WORK_SEQ + 1))
  WORK="$SUITE_TMP/w$_WORK_SEQ-$1"
  SLUG=${2:-ui-conformance}
  NESTED="$WORK/nested"
  mkdir -p "$NESTED/src/routes/settings" "$NESTED/src/routes/onboarding"

  # Deliberately no package.json and no .git — in $WORK or in $NESTED. The whole
  # point of this tree is that nothing in it says "a project starts here".
  cat > "$NESTED/src/routes/settings/billing.tsx" <<'EOF'
export function Billing() {
  return <section><h2>Billing</h2><p>No invoices</p></section>;
}
EOF
  cat > "$NESTED/src/routes/settings/profile.tsx" <<'EOF'
export function Profile() {
  return <form><label>Display name</label><input name="display" /></form>;
}
EOF
  cat > "$NESTED/src/routes/onboarding/welcome.tsx" <<'EOF'
export function Welcome() {
  return <main><h1>Welcome</h1><button>Get started</button></main>;
}
EOF
  cp "$FIXTURES/units-3.json" "$NESTED/units.json"
  cp "$FIXTURES/deliberation.json" "$NESTED/deliberation.json"
  note "markerless workdir $WORK (nested $NESTED, slug $SLUG)"
}

# nearest_ancestor_ponder <dir>
# The nearest directory at or above <dir> that holds a .ponder, or nothing. A
# machine can have a stray ~/.ponder or /tmp/.ponder left by real work, and a
# test that needs "no session store anywhere above me" has to be able to ask
# rather than assume.
nearest_ancestor_ponder() {
  _nap_dir=$1
  while [ -n "$_nap_dir" ] && [ "$_nap_dir" != '/' ]; do
    if [ -d "$_nap_dir/.ponder" ]; then printf '%s' "$_nap_dir"; return 0; fi
    _nap_dir=$(dirname "$_nap_dir")
  done
  [ -d "/.ponder" ] && printf '/'
  return 0
}

# sess <relative-path>   -> absolute path inside the session directory
sess() { printf '%s' "$WORK/.ponder/$SLUG/$1"; }

# pass_dir <n>           -> absolute path to passes/NN, tolerating an unpadded NN
pass_dir() {
  _pd_padded=$(printf '%02d' "$1")
  if [ -d "$WORK/.ponder/$SLUG/passes/$_pd_padded" ]; then
    printf '%s' "$WORK/.ponder/$SLUG/passes/$_pd_padded"
  else
    printf '%s' "$WORK/.ponder/$SLUG/passes/$1"
  fi
}

# finding_id <1-based-index>  -> the engine-assigned id at that position
finding_id() { jget "$(sess findings.json)" "d.findings[$(($1 - 1))].id"; }

# delta_file <fixture-basename>  -> path to a copy with @FN@ replaced by real ids
# Delta fixtures never hard-code finding ids: the engine owns id assignment, so
# the suite resolves them from findings.json at the moment the delta is applied.
delta_file() {
  _df_dest="$WORK/applied-$1"
  _df_args=''
  _df_i=1
  while [ "$_df_i" -le 16 ]; do
    _df_id=$(finding_id "$_df_i")
    if [ -n "$_df_id" ]; then
      _df_args="$_df_args -e s/@F$_df_i@/$_df_id/g"
    fi
    _df_i=$((_df_i + 1))
  done
  # shellcheck disable=SC2086
  sed $_df_args "$FIXTURES/$1" > "$_df_dest"
  printf '%s' "$_df_dest"
}

# hash_tree  -> checksum of every file in $WORK except the .ponder directory
hash_tree() {
  ( cd "$WORK" && find . -path ./.ponder -prune -o -type f -print \
      | LC_ALL=C sort \
      | while IFS= read -r f; do $HASHER "$f"; done )
}

# ------------------------------------------------------------ running the CLI --

note() {
  [ "${VERBOSE:-0}" = "1" ] && printf '%s\n' "      ${C_DIM}# $*${C_OFF}" >&2
  return 0
}

# _shellquote <args...> — render an invocation that can be pasted into a shell.
# Verbose output is only useful if you can rerun the failing command by hand.
_shellquote() {
  printf 'ponder%s' "$(_quote_args "$@")"
}

_quote_args() {
  _sq_out=''
  for _sq_a in "$@"; do
    case "$_sq_a" in
      '' | *[!A-Za-z0-9_./=@:,+-]*)
        _sq_out="$_sq_out '$(printf '%s' "$_sq_a" | sed "s/'/'\\\\''/g")'" ;;
      *)
        _sq_out="$_sq_out $_sq_a" ;;
    esac
  done
  printf '%s' "$_sq_out"
}

_capture() {
  OUT=$(cat "$SUITE_TMP/out")
  ERR=$(cat "$SUITE_TMP/err")
  ALL="$OUT
$ERR"
}

# run_ponder <args...>
# stdin is /dev/null so a command that wrongly waits on it fails fast instead of
# hanging the suite.
run_ponder() {
  LAST_CMD=$(_shellquote "$@")
  [ "${VERBOSE:-0}" = "1" ] && printf '%s\n' "      ${C_DIM}\$ $LAST_CMD${C_OFF}" >&2
  TIMED_OUT=0
  _rp_t0=$(date +%s)
  ( cd "$WORK" && "$PONDER_BIN" "$@" ) > "$SUITE_TMP/out" 2> "$SUITE_TMP/err" < /dev/null
  STATUS=$?
  ELAPSED=$(( $(date +%s) - _rp_t0 ))
  _capture
  [ "${VERBOSE:-0}" = "1" ] && printf '%s\n' "      ${C_DIM}-> exit $STATUS (${ELAPSED}s)${C_OFF}" >&2
  return 0
}

# run_ponder_in <dir> <args...>
# Same as run_ponder, but from a directory of the test's choosing rather than
# $WORK. Where a command is run is itself part of the contract: the engine
# resolves the project root by walking up from the working directory, so the
# only way to test that walk is to run from somewhere other than the root.
run_ponder_in() {
  _ri_dir=$1; shift
  LAST_CMD="(cd $_ri_dir && $(_shellquote "$@"))"
  [ "${VERBOSE:-0}" = "1" ] && printf '%s\n' "      ${C_DIM}\$ $LAST_CMD${C_OFF}" >&2
  TIMED_OUT=0
  _ri_t0=$(date +%s)
  ( cd "$_ri_dir" && "$PONDER_BIN" "$@" ) > "$SUITE_TMP/out" 2> "$SUITE_TMP/err" < /dev/null
  STATUS=$?
  ELAPSED=$(( $(date +%s) - _ri_t0 ))
  _capture
  [ "${VERBOSE:-0}" = "1" ] && printf '%s\n' "      ${C_DIM}-> exit $STATUS (${ELAPSED}s)${C_OFF}" >&2
  return 0
}

# run_ponder_stdin <file> <args...>   feeds the file on stdin
run_ponder_stdin() {
  _rs_file=$1; shift
  LAST_CMD="$(_shellquote "$@") < $(basename "$_rs_file")"
  [ "${VERBOSE:-0}" = "1" ] && printf '%s\n' "      ${C_DIM}\$ $LAST_CMD${C_OFF}" >&2
  TIMED_OUT=0
  _rs_t0=$(date +%s)
  ( cd "$WORK" && "$PONDER_BIN" "$@" ) > "$SUITE_TMP/out" 2> "$SUITE_TMP/err" < "$_rs_file"
  STATUS=$?
  ELAPSED=$(( $(date +%s) - _rs_t0 ))
  _capture
  return 0
}

# run_ponder_limit <seconds> <args...>
# Same as run_ponder with a watchdog. Used by the OCA group, where the whole
# point is that a sick database cannot hold the engine open.
#
# The watchdog is bounded by the wall clock, not by a count of poll iterations:
# on a loaded machine each iteration costs more than the sleep it contains, so
# counting iterations would let a genuinely hung process run far past the limit
# and report TIMED_OUT=0 with a wildly wrong ELAPSED.
run_ponder_limit() {
  _rl_limit=$1; shift
  LAST_CMD=$(_shellquote "$@")
  [ "${VERBOSE:-0}" = "1" ] && printf '%s\n' "      ${C_DIM}\$ $LAST_CMD  (limit ${_rl_limit}s)${C_OFF}" >&2
  TIMED_OUT=0
  _rl_t0=$(date +%s)
  ( cd "$WORK" && "$PONDER_BIN" "$@" ) > "$SUITE_TMP/out" 2> "$SUITE_TMP/err" < /dev/null &
  _rl_pid=$!
  while kill -0 "$_rl_pid" 2>/dev/null; do
    if [ $(( $(date +%s) - _rl_t0 )) -ge "$_rl_limit" ]; then
      kill -9 "$_rl_pid" 2>/dev/null
      TIMED_OUT=1
      break
    fi
    sleep "$POLL_SLEEP"
  done
  wait "$_rl_pid" 2>/dev/null
  STATUS=$?
  ELAPSED=$(( $(date +%s) - _rl_t0 ))
  _capture
  [ "${VERBOSE:-0}" = "1" ] && printf '%s\n' "      ${C_DIM}-> exit $STATUS (${ELAPSED}s, timed_out=$TIMED_OUT)${C_OFF}" >&2
  return 0
}

# run_ponder_tty <args...>
# Runs the CLI with stdout attached to a pty, so the tests that care about
# colour can tell "the engine chose not to colour" from "the pipe hid it".
# Sets TTY_OUT to the combined output; returns 1 when this machine has no
# usable `script`, so callers can degrade to a warning instead of a failure.
TTY_OUT=''
run_ponder_tty() {
  TTY_OUT=''
  [ -n "$TTY_STYLE" ] || return 1
  LAST_CMD="$(_shellquote "$@")  # on a pty"
  [ "${VERBOSE:-0}" = "1" ] && printf '%s\n' "      ${C_DIM}\$ $LAST_CMD${C_OFF}" >&2
  if [ "$TTY_STYLE" = bsd ]; then
    ( cd "$WORK" && script -q /dev/null "$PONDER_BIN" "$@" ) > "$SUITE_TMP/tty" 2>&1 < /dev/null
  else
    ( cd "$WORK" && script -qec "$(_quote_args "$PONDER_BIN" "$@")" /dev/null ) \
      > "$SUITE_TMP/tty" 2>&1 < /dev/null
  fi
  TTY_OUT=$(cat "$SUITE_TMP/tty")
  return 0
}

# run_ponder_pair <fileA> <fileB> <args-with-@FILE@...>
# Fires two invocations at once and records their exit codes in PAIR_RC_A and
# PAIR_RC_B. Nothing in SPEC.md describes concurrent use, so the tests built on
# this assert only that the store survives it.
PAIR_RC_A=0 ; PAIR_RC_B=0
run_ponder_pair() {
  _pp_a=$1; _pp_b=$2; shift 2
  # The two command lines are built as quoted strings and run through eval, so
  # an argument with a space in it — every --why in the suite — survives.
  _pp_argsa='' ; _pp_argsb=''
  for _pp_x in "$@"; do
    case "$_pp_x" in
      @FILE@)
        _pp_argsa="$_pp_argsa$(_quote_args "$_pp_a")"
        _pp_argsb="$_pp_argsb$(_quote_args "$_pp_b")" ;;
      *)
        _pp_q=$(_quote_args "$_pp_x")
        _pp_argsa="$_pp_argsa$_pp_q"
        _pp_argsb="$_pp_argsb$_pp_q" ;;
    esac
  done
  _pp_bin=$(_quote_args "$PONDER_BIN")
  LAST_CMD="ponder$_pp_argsa  &  ponder$_pp_argsb"
  [ "${VERBOSE:-0}" = "1" ] && printf '%s\n' "      ${C_DIM}\$ $LAST_CMD${C_OFF}" >&2
  ( cd "$WORK" && eval "$_pp_bin$_pp_argsa" ) > "$SUITE_TMP/pair-a" 2>&1 < /dev/null &
  _pp_pa=$!
  ( cd "$WORK" && eval "$_pp_bin$_pp_argsb" ) > "$SUITE_TMP/pair-b" 2>&1 < /dev/null &
  _pp_pb=$!
  wait "$_pp_pa"; PAIR_RC_A=$?
  wait "$_pp_pb"; PAIR_RC_B=$?
  [ "${VERBOSE:-0}" = "1" ] && printf '%s\n' "      ${C_DIM}-> exit $PAIR_RC_A / $PAIR_RC_B${C_OFF}" >&2
  return 0
}

# --------------------------------------------------------------- assertions --

_assert_pass() { ASSERTS=$((ASSERTS + 1)); }

_assert_fail() {
  ASSERTS=$((ASSERTS + 1))
  ASSERT_FAILS=$((ASSERT_FAILS + 1))
  FAIL_MSGS="${FAIL_MSGS}      - $1
"
}

_excerpt() {
  printf '%s\n' "$1" | head -25 | sed 's/^/          | /'
}

fail() { _assert_fail "$1"; }

# kv_row <text> <key>
#
# Reassemble one row of a `fmt.kv` two-column block into the single logical value
# the engine was handed, whatever width it happened to be laid out at.
#
# `ponder start` wraps a long kv value to terminal width and hangs the
# continuations under the value column (SPEC 7 lets prose wrap; only a
# command-shaped line inside an `enumerate` block is byte-for-byte). A test that
# greps one physical line therefore asserts a layout, not a contract — and the
# lens scales are 143-204 characters, so at any real width they wrap. This joins
# the key's line to every following line indented at least as far as its value
# column, which is exactly the set of lines the renderer hung there, and stops at
# the next key, a blank line, or anything less indented.
kv_row() {
  printf '%s\n' "$1" | awk -v key="$2" '
    !seen && $0 ~ "^[[:space:]]*" key "[[:space:]]" {
      seen = 1
      match($0, /^[[:space:]]*/); keyind = RLENGTH
      rest = substr($0, keyind + length(key) + 1)
      match(rest, /^[[:space:]]*/); valcol = keyind + length(key) + RLENGTH
      out = substr(rest, RLENGTH + 1)
      next
    }
    seen {
      match($0, /^[[:space:]]*/)
      if (RLENGTH < valcol || $0 ~ /^[[:space:]]*$/) exit
      out = out " " substr($0, RLENGTH + 1)
    }
    END { if (seen) print out }
  '
}

warn() {
  WARNINGS=$((WARNINGS + 1))
  printf '    %s%s %s%s\n' "$C_YEL" "$MARK_WARN" "$1" "$C_OFF"
}

# assert_status <expected> <label>   — checks the last run's exit code
assert_status() {
  if [ "$STATUS" -eq "$1" ]; then
    _assert_pass
  else
    _assert_fail "$2: expected exit $1, got $STATUS from \`$LAST_CMD\`
$(_excerpt "$ALL")"
  fi
}

assert_status_not() {
  if [ "$STATUS" -ne "$1" ]; then
    _assert_pass
  else
    _assert_fail "$2: expected any exit but $1 from \`$LAST_CMD\`
$(_excerpt "$ALL")"
  fi
}

assert_eq() {
  if [ "$1" = "$2" ]; then _assert_pass; else
    _assert_fail "$3: expected [$1], got [$2]"
  fi
}

assert_ne() {
  if [ "$1" != "$2" ]; then _assert_pass; else
    _assert_fail "$3: expected anything but [$1]"
  fi
}

# assert_match <text> <extended-regex> <label>
assert_match() {
  if printf '%s\n' "$1" | grep -Eq -- "$2"; then _assert_pass; else
    _assert_fail "$3: no match for /$2/ in:
$(_excerpt "$1")"
  fi
}

assert_imatch() {
  if printf '%s\n' "$1" | grep -Eiq -- "$2"; then _assert_pass; else
    _assert_fail "$3: no case-insensitive match for /$2/ in:
$(_excerpt "$1")"
  fi
}

assert_no_match() {
