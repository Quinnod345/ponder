    _assert_pass
  else
    _assert_fail "$4: expected [$1] within $3 of $2"
  fi
}

# assert_json_stdout <label>  — the last run's stdout must be one JSON document
assert_json_stdout() {
  _aj_err=$(json_parses "$OUT")
  if [ -z "$_aj_err" ]; then
    _assert_pass
  else
    _assert_fail "$1: \`$LAST_CMD\` did not emit parseable JSON on stdout
$(_excerpt "$_aj_err")"
  fi
}

# assert_next <label>  — the NEXT: line the whole protocol depends on
assert_next() {
  if printf '%s\n' "$ALL" | grep -Eq '^[[:space:]]*NEXT:'; then
    _assert_pass
  else
    _assert_fail "$1: no NEXT: line from \`$LAST_CMD\`
$(_excerpt "$ALL")"
  fi
}

# assert_json_next <label>
# SPEC 8.6 in --json mode: the phase the agent now owes has to survive into the
# machine-readable output too, or a --json-only agent loses the thread the
# moment its context is compacted. A `NEXT:` line printed alongside the document
# would break assert_json_stdout, so the payload has to carry it.
assert_json_next() {
  _jn_file="$SUITE_TMP/json-next.json"
  printf '%s' "$OUT" > "$_jn_file"
  _jn_phase=$(jget "$_jn_file" 'd.next && (d.next.phase || d.next.command)')
  if [ -n "$_jn_phase" ]; then
    _assert_pass
  else
    _assert_fail "$1: \`$LAST_CMD\` emitted JSON with no next phase in it
$(_excerpt "$OUT")"
  fi
}

# jout <js-expression-over-d>  — read the last run's JSON stdout
jout() {
  printf '%s' "$OUT" > "$SUITE_TMP/json-out.json"
  jget "$SUITE_TMP/json-out.json" "$1"
}

