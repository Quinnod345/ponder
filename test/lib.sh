# run_test <name> <function>
run_test() {
  case "$1" in
    *"$FILTER"*) ;;
    *) return 0 ;;
  esac

  if [ "${LIST_ONLY:-0}" = "1" ]; then
    printf '%s\n' "$1"
    return 0
  fi

  TEST_NAME=$1
  TESTS_RUN=$((TESTS_RUN + 1))
  ASSERTS=0
  ASSERT_FAILS=0
  FAIL_MSGS=''

  # Nothing carries over from the previous test. A test that forgets its
  # new_workdir must fail on its own missing state, not quietly assert against
  # the last test's session — and the last run's OUT must never be what a fresh
  # test's first assertion reads.
  WORK=''
  SLUG=''
  STATUS=0
  OUT=''; ERR=''; ALL=''; TTY_OUT=''
  ELAPSED=0; TIMED_OUT=0; LAST_CMD=''
  JSON_FLAG=''
  JUDGE_JSON=''; JUDGE_VERDICT=''; JUDGE_REASON=''

  [ "${VERBOSE:-0}" = "1" ] && printf '%s\n' "  ${C_CYN}── $1${C_OFF}"

  _rt_path=$PATH
  "$2"

  # No test may leak environment into the next one: the OCA group turns the
  # bridge on and puts stub binaries on PATH.
  PATH=$_rt_path
  export PATH PONDER_OCA=off
  unset PONDER_OCA_DSN 2>/dev/null || true
  JSON_FLAG=''

  if [ "$ASSERT_FAILS" -eq 0 ]; then
    TESTS_PASSED=$((TESTS_PASSED + 1))
    printf '  %s%s%s %s %s(%s checks)%s\n' \
      "$C_GRN" "$MARK_OK" "$C_OFF" "$1" "$C_DIM" "$ASSERTS" "$C_OFF"
  else
    TESTS_FAILED=$((TESTS_FAILED + 1))
    FAILED_NAMES="$FAILED_NAMES$1
"
    printf '  %s%s%s %s %s(%s of %s checks failed)%s\n' \
      "$C_RED" "$MARK_BAD" "$C_OFF" "$1" "$C_DIM" "$ASSERT_FAILS" "$ASSERTS" "$C_OFF"
    printf '%s%s%s' "$C_RED" "$FAIL_MSGS" "$C_OFF"
  fi

  if [ "${KEEP:-0}" != "1" ] && [ -n "$WORK" ] && [ -d "$WORK" ]; then
    rm -rf "$WORK"
  fi
}
